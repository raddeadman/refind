ROLES = ("anonymous", "user", "officer", "admin")
OUT = Path(__file__).resolve().parents[2] / "docs" / "evidence" / "rbac_matrix.md"

NEW_ITEM = {"type": "lost", "title": "Blue umbrella", "category": "wallets", "location": {"building": "Library"},
            "date": (datetime.now(UTC) - timedelta(days=1)).date().isoformat()}


@dataclass
class Endpoint:
    label: str
    method: str
    path: Callable[[dict], str]
    expected: tuple[int, int, int, int]  # anonymous, user, officer, admin
    body: Callable[[dict], dict] | None = None
    prepare: Callable | None = None


async def _approve_claim(world: dict) -> None:
    await world["claim"].set({"status": ClaimStatus.approved})
    await (await Item.get(world["found"].id)).set({"status": ItemStatus.claimed})


ENDPOINTS = [
    Endpoint("Search found items", "GET", lambda w: "/api/items", (200, 200, 200, 200)),
    Endpoint("Search lost reports", "GET", lambda w: "/api/items?type=lost", (403, 403, 200, 200)),
    Endpoint("Report an item", "POST", lambda w: "/api/items", (401, 201, 201, 201), body=lambda w: NEW_ITEM),
    Endpoint("Edit someone else's item", "PATCH", lambda w: f"/api/items/{w['found'].id}", (401, 403, 200, 200),
             body=lambda w: {"version": w["found"].version, "heldAt": "Desk 2"}),
    Endpoint("My matches", "GET", lambda w: "/api/matches/mine", (401, 200, 200, 200)),
    Endpoint("All matches", "GET", lambda w: "/api/matches", (401, 403, 200, 200)),
    Endpoint("Confirm a match", "PATCH", lambda w: f"/api/matches/{w['match'].id}", (401, 403, 200, 200),
             body=lambda w: {"status": "confirmed"}),
    Endpoint("My claims", "GET", lambda w: "/api/claims/mine", (401, 200, 200, 200)),
    Endpoint("Claim review queue", "GET", lambda w: "/api/claims/review", (401, 403, 200, 200)),
    Endpoint("Approve a claim", "POST", lambda w: f"/api/claims/{w['claim'].id}/approve", (401, 403, 200, 200)),
    Endpoint("Record a handover", "POST", lambda w: f"/api/claims/{w['claim'].id}/handover", (401, 403, 200, 200),
             body=lambda w: {"idChecked": True, "idLast4": "1234"}, prepare=_approve_claim),
    Endpoint("My notifications", "GET", lambda w: "/api/notifications", (401, 200, 200, 200)),
    Endpoint("Create a category", "POST", lambda w: "/api/categories", (401, 403, 403, 201),
             body=lambda w: {"code": "keys", "name": "Keys"}),
]

RESULTS: dict[tuple[str, str], int] = {}


@pytest.fixture(scope="module", autouse=True)
def write_matrix():
    yield
    if not os.environ.get("EVIDENCE") or len(RESULTS) != len(ENDPOINTS) * len(ROLES):
        return  # only part of the matrix ran (e.g. -k); keep the last full table
    rows = ["| Endpoint | Method and path | " + " | ".join(r.capitalize() for r in ROLES) + " |",
            "| --- | --- | " + " | ".join("---" for _ in ROLES) + " |"]
    for e in ENDPOINTS:
        path = e.path({"found": _Id("{itemId}"), "match": _Id("{matchId}"), "claim": _Id("{claimId}")})
        rows.append(f"| {e.label} | `{e.method} {path}` | " + " | ".join(str(RESULTS[(e.label, r)]) for r in ROLES)
                    + " |")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "# RBAC test matrix\n\n"
        "Generated by `backend/tests/test_rbac_matrix.py`: every cell is a separate test on fresh data and "
        "matched the expected code.\n401 = not logged in, 403 = logged in without the role (or, for lost "
        "reports, not allowed to see private data).\n\n" + "\n".join(rows) + "\n"
    )


class _Id:
    def __init__(self, text: str):
        self.id, self.version = text, 1


@pytest.fixture
async def world(make_user):
    """A found item reported at the desk, a matched lost report and a pending claim from its owner."""
    await Category(code="wallets", name="Wallets").insert()
    desk, owner = await make_user(Role.officer), await make_user()
    day = datetime.now(UTC) - timedelta(days=1)
    found = await Item(type="found", title="Black wallet", category="wallets", location={"building": "Library"},
                       date=day, reporterId=desk.id, status=ItemStatus.matched).insert()
    lost = await Item(type="lost", title="My wallet", category="wallets", location={"building": "Library"},
                      date=day, reporterId=owner.id, status=ItemStatus.matched).insert()
    match = await Match(lostItemId=lost.id, foundItemId=found.id, score=80).insert()
    claim = await Claim(itemId=found.id, claimantId=owner, matchId=match.id,
                        answers=[ClaimAnswer(question="Name on the card?", answer="Ahmed")]).insert()
    return {"found": found, "lost": lost, "match": match, "claim": claim}


@pytest.mark.parametrize("role", ROLES)
@pytest.mark.parametrize("endpoint", ENDPOINTS, ids=[e.label for e in ENDPOINTS])
async def test_rbac(client, make_user, world, endpoint: Endpoint, role: str):
    if endpoint.prepare:
        await endpoint.prepare(world)
    headers = {} if role == "anonymous" else auth(await make_user(Role(role)))
    body = endpoint.body(world) if endpoint.body else None
    response = await client.request(endpoint.method, endpoint.path(world), json=body, headers=headers)
    expected = endpoint.expected[ROLES.index(role)]
    RESULTS[(endpoint.label, role)] = response.status_code
    assert response.status_code == expected, response.text
